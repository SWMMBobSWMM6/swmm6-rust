#!/usr/bin/env python3
"""Generate the coupled 1D-2D gate decks in gate/decks/twodc/.

Upstream's tree has one deck that maps mesh points to 1D nodes (examples/2d_complete_example.inp,
also copied into tests and docs). These decks start from it and vary one thing at a time, so the
2D solver's and the coupling's code paths each have a deck that reaches them:

  base decks   lot (the example, without OUTPUT_FILE), spill (a junction whose pipe is too small
               for its inflow surcharges onto the mesh and drains back), outfall and outfall_gated
               (a 1D outfall discharging onto a mesh cell), quads (a mixed triangle/quad mesh),
               infil_<method> (rain on the mesh with each 2D infiltration method), kinwave and
               steady (the other 1D routing methods), gages (two located rain gages)
  option decks lot and spill, each with one [2D_OPTIONS] key set to a non-default value

Both reference builds read them: the 2D build runs them, the 1D build skips the [2D_*] sections
with a warning, so they are 1D gate decks too. Run from anywhere: `python3 gate/twodc_gen.py`.

Written for swmm6-rust, 12 November 2026, by Claude (Anthropic) for Robert Dickinson. The base
deck is derived from OpenSWMM's examples/2d_complete_example.inp (Copyright 2026 Caleb Buahin,
Apache License, Version 2.0); the header of each generated deck says so.
"""
import os, re

H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = '/root/work/swmm6src/upstream/examples/2d_complete_example.inp'
OUT = os.path.join(H, 'gate', 'decks', 'twodc')

HEADER = (';; swmm6-rust gate deck {name}: {what}\n'
          ';; Generated by gate/twodc_gen.py from OpenSWMM examples/2d_complete_example.inp\n'
          ';; (HydroCouple/openswmm.engine, swmm6_rel @ 88329d6, Copyright 2026 Caleb Buahin,\n'
          ';; Apache License 2.0), modified for the 2D gate. Not an OpenSWMM file.\n')


def sections(text):
    """Split a deck into an ordered list of (header or None, body text)."""
    out, cur, buf = [], None, []
    for line in text.split('\n'):
        m = re.match(r'^\[([^\]]+)\]', line)
        if m:
            out.append((cur, '\n'.join(buf)))
            cur, buf = m.group(1).upper(), []
        else:
            buf.append(line)
    out.append((cur, '\n'.join(buf)))
    return out


def join(secs):
    parts = []
    for name, body in secs:
        parts.append(body if name is None else '[%s]\n%s' % (name, body))
    return '\n'.join(parts).rstrip('\n') + '\n'


def get(secs, name):
    for n, b in secs:
        if n == name:
            return b
    return None


def put(secs, name, body, after=None):
    """Replace a section's body, or add the section (after `after`, else at the end)."""
    for i, (n, b) in enumerate(secs):
        if n == name:
            secs[i] = (n, body)
            return secs
    pos = len(secs)
    if after is not None:
        for i, (n, b) in enumerate(secs):
            if n == after:
                pos = i + 1
    secs.insert(pos, (name, body))
    return secs


def drop(secs, name):
    return [(n, b) for n, b in secs if n != name]


def set_opt(body, key, value):
    """Set a [2D_OPTIONS] or [OPTIONS] key (replace the row, or append it)."""
    lines = body.split('\n')
    for i, l in enumerate(lines):
        t = l.split()
        if t and t[0].upper() == key:
            lines[i] = '%-23s %s' % (key, value)
            return '\n'.join(lines)
    # append before trailing blank lines
    j = len(lines)
    while j > 0 and not lines[j - 1].strip():
        j -= 1
    lines.insert(j, '%-23s %s' % (key, value))
    return '\n'.join(lines)


def del_opt(body, key):
    return '\n'.join(l for l in body.split('\n') if not (l.split() and l.split()[0].upper() == key))


def base_lot():
    t = open(SRC, encoding='utf-8').read()
    # keep the ;; UNITS / SOURCE_CRS prescan headers, drop the long banner
    t = re.sub(r'^;;={10,}.*?;;={10,}\n', '', t, count=1, flags=re.S)
    s = sections(t)
    s = put(s, '2D_OPTIONS', del_opt(get(s, '2D_OPTIONS'), 'OUTPUT_FILE'))
    return s


def base_spill():
    s = base_lot()
    # a hydrograph into J1 bigger than C1 (0.30 m at 1%, about 0.1 m3/s full) can carry
    ts = get(s, 'TIMESERIES')
    ts += ('\n;; inflow to J1 (m3/s): rises past the pipe capacity, then recedes\n'
           'SPILL_TS    01/01/2024   00:00  0.00\n'
           'SPILL_TS                 00:30  0.25\n'
           'SPILL_TS                 01:30  0.25\n'
           'SPILL_TS                 02:30  0.00\n'
           'SPILL_TS                 06:00  0.00\n')
    s = put(s, 'TIMESERIES', ts)
    s = put(s, 'INFLOWS', ';;Node  Constituent  Time Series  Type  Mfactor  Sfactor  Baseline  Pattern\n'
                          'J1      FLOW         SPILL_TS     FLOW  1.0      1.0\n\n', after='CURVES')
    o = get(s, '2D_OPTIONS')
    o = set_opt(o, 'RAINFALL_MODE', 'NONE')
    s = put(s, '2D_OPTIONS', o)
    return s


def base_outfall(gated):
    s = base_lot()
    j = get(s, 'JUNCTIONS').rstrip('\n') + '\nJX      101.5      1.0       0.0        0.0       0.0\n\n'
    s = put(s, 'JUNCTIONS', j)
    o = get(s, 'OUTFALLS').rstrip('\n') + '\nOUT3    100.0      FREE   *          %s\n\n' % ('YES' if gated else 'NO')
    s = put(s, 'OUTFALLS', o)
    c = get(s, 'CONDUITS').rstrip('\n') + '\nCX      JX        OUT3     40     0.013      0         0          0         0\n\n'
    s = put(s, 'CONDUITS', c)
    x = get(s, 'XSECTIONS').rstrip('\n') + '\nCX      CIRCULAR  0.25   0      0      0      1\n\n'
    s = put(s, 'XSECTIONS', x)
    ts = get(s, 'TIMESERIES') + ('\nJX_TS       01/01/2024   00:00  0.00\nJX_TS                    00:20  0.08\n'
                                 'JX_TS                    01:40  0.08\nJX_TS                    02:00  0.00\n'
                                 'JX_TS                    06:00  0.00\n')
    s = put(s, 'TIMESERIES', ts)
    s = put(s, 'INFLOWS', ';;Node  Constituent  Time Series  Type  Mfactor  Sfactor  Baseline  Pattern\n'
                          'JX      FLOW         JX_TS        FLOW  1.0      1.0\n\n', after='CURVES')
    m = get(s, '2D_TRIANGLE_NODE_MAP').rstrip('\n') + \
        '\n   0                 OUT3        0.65   0.5       ;; SW-lower cell receives the outfall\n\n'
    s = put(s, '2D_TRIANGLE_NODE_MAP', m)
    return s


def base_quads():
    s = base_lot()
    # SW and SE squares as quads; NW and NE as the example's triangle pairs
    s = put(s, '2D_TRIANGLES', ';; V1  V2  V3   MANNINGS_N   TAG\n'
                               '   3   4   7    0.018        ;; NW lower\n'
                               '   3   7   6    0.018        ;; NW upper\n'
                               '   4   5   8    0.018  vault ;; NE lower (couples to ST1)\n'
                               '   4   8   7    0.018        ;; NE upper\n\n')
    s = put(s, '2D_QUADS', ';;V1  V2  V3  V4  N      INIT_DEPTH  TAG\n'
                           '0     1   4   3   0.018  0.0         SWQ\n'
                           '1     2   5   4   0.018  0.0         SEQ\n\n', after='2D_TRIANGLES')
    s = put(s, '2D_BOUNDARY_CONDITIONS', ';; TRI EDGE TYPE PARAM_1 PARAM_2 GROUP\n'
                                         '   3     0      SPECIFIED_FLOW    0.0500          *         upstream\n'
                                         '   1     0      SPECIFIED_STAGE   101.50          *         *\n\n')
    s = put(s, '2D_EDGE_CONVEYANCE', ';; FROM_VERTEX  TO_VERTEX  CONVEYANCE\n   3            4          0.30\n\n')
    return s


INFIL = {
    'HORTON': '* HORTON 76.2 10.16 4 0.1 254.0 LOST',
    'MODIFIED_HORTON': '* MODIFIED_HORTON 76.2 10.16 4 0.1 254.0 LOST',
    'GREEN_AMPT': '* GREEN_AMPT 101.6 12.7 0.3 0 0 LOST',
    'MODIFIED_GREEN_AMPT': '* MODIFIED_GREEN_AMPT 101.6 12.7 0.3 0 0 LOST',
    'CURVE_NUMBER': '* CURVE_NUMBER 75 0 0.5 0 0 LOST',
    'CONSTANT': '* CONSTANT 12.7 0 0 0 0 LOST',
}


def base_infil(method):
    s = base_lot()
    ts = get(s, 'TIMESERIES').replace('RAIN_TS     01/01/2024   00:00  5.0', 'RAIN_TS     01/01/2024   00:00  40.0') \
                             .replace('RAIN_TS                  02:00  5.0', 'RAIN_TS                  02:00  40.0')
    s = put(s, 'TIMESERIES', ts)
    s = put(s, '2D_OPTIONS', set_opt(get(s, '2D_OPTIONS'), 'INFILTRATION', 'YES'))
    s = put(s, '2D_INFILTRATION_DEFAULTS', INFIL[method] + '\n\n', after='2D_EDGE_CONVEYANCE')
    return s


def base_uncoupled():
    s = base_lot()
    s = drop(drop(s, '2D_VERTEX_NODE_MAP'), '2D_TRIANGLE_NODE_MAP')
    return s


# Coriolis, turbulence and wall drag need FULL_SWE on a global step (LTS_TIERS 1) and an
