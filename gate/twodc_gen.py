def write(name, what, secs):
    p = os.path.join(OUT, name + '.inp')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER.format(name=name, what=what))
        f.write(join(secs))
    return p


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.inp'):
            os.remove(os.path.join(OUT, f))
    n = 0
    bases = {
        'lot': ('the coupled example (vertex-coupled junction, triangle-coupled storage, every BC type)', base_lot),
        'spill': ('a surcharging junction spills onto the mesh and drains back', base_spill),
    }
    for name, (what, fn) in bases.items():
        write(name, what, fn()); n += 1
    write('outfall', 'a 1D outfall discharges onto a mesh cell', base_outfall(False)); n += 1
    write('outfall_gated', 'a gated 1D outfall discharges onto a mesh cell', base_outfall(True)); n += 1
    write('quads', 'a mixed triangle/quad mesh, coupled', base_quads()); n += 1
    for m in INFIL:
        write('infil_' + m.lower(), 'rain on the mesh with %s infiltration' % m, base_infil(m)); n += 1
    for m in ('KINWAVE', 'STEADY'):
        write('routing_' + m.lower(), 'the coupled example under FLOW_ROUTING %s' % m, base_routing(m)); n += 1
    for mode in ('NATURAL_NEIGHBOUR', 'NEAREST_NEIGHBOUR', 'SYSTEM', 'NONE'):
        s = base_gages()
        s = put(s, '2D_OPTIONS', set_opt(get(s, '2D_OPTIONS'), 'RAINFALL_MODE', mode))
        write('gages_' + mode.lower(), 'two located gages, RAINFALL_MODE %s' % mode, s); n += 1
    for bname, (bwhat, fn) in bases.items():
        for vname, kv in OPTION_VARIANTS:
            s = fn()
            o = get(s, '2D_OPTIONS')
            for k, v in kv:
                o = set_opt(o, k, v)
            s = put(s, '2D_OPTIONS', o)
            write('%s_%s' % (bname, vname), '%s; %s' % (bwhat, ', '.join('%s %s' % kv_ for kv_ in kv)), s); n += 1
    write('uncoupled', 'the example mesh with no node maps', base_uncoupled()); n += 1
    for vname, kv in UNCOUPLED_VARIANTS:
        s = base_uncoupled()
        o = get(s, '2D_OPTIONS')
        for k, v in [('MOMENTUM_EQUATION', 'FULL_SWE'), ('LTS_TIERS', '1')] + kv:
            o = set_opt(o, k, v)
        s = put(s, '2D_OPTIONS', o)
        write('uncoupled_' + vname, 'uncoupled mesh, FULL_SWE, LTS_TIERS 1; ' + ', '.join('%s %s' % kv_ for kv_ in kv), s); n += 1
    # error paths, on purpose: an option value open() rejects, and a combination initialize() rejects
    s = base_lot(); s = put(s, '2D_OPTIONS', set_opt(get(s, '2D_OPTIONS'), 'COUPLING_COEFFS', 'AUTO'))
    write('err_open_coeffs', 'COUPLING_COEFFS AUTO, which open() rejects (exit 5)', s); n += 1
    s = base_lot(); s = put(s, '2D_OPTIONS', set_opt(get(s, '2D_OPTIONS'), 'TURBULENCE_MODEL', 'SMAGORINSKY'))
    write('err_init_turbulence', 'SMAGORINSKY under LOCAL_INERTIAL with LTS, which 2D initialization rejects', s); n += 1
    s = base_lot(); o = get(s, '2D_OPTIONS')
    for k, v in [('MOMENTUM_EQUATION', 'FULL_SWE'), ('LTS_TIERS', '1'), ('CORIOLIS', 'LATITUDE'), ('CORIOLIS_LATITUDE', '40')]:
        o = set_opt(o, k, v)
    s = put(s, '2D_OPTIONS', o)
    write('err_init_coupled_coriolis', 'Coriolis on a coupled mesh, which 2D initialization rejects', s); n += 1
    print('twodc_gen: %d decks in %s' % (n, OUT))


if __name__ == '__main__':
    main()
