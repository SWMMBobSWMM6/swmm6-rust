#!/usr/bin/env python3
"""Generate the uncoupled 2D step gate decks in gate/decks/twods/.

Upstream's uncoupled 2D decks are small (at most 8 cells) and use few of the marcher's options.
These decks put a structured mesh (triangles, quads or both, uniform or graded spacing) over a
sloped bed with a bump, add a small 1D network that does not touch the mesh, and vary one thing
at a time so each path of the 2D time step has a deck that reaches it:

  momentum     LOCAL_INERTIAL, DIFFUSIVE_WAVE, FULL_SWE (LTS and global), FULL_SWE with
               RECONSTRUCTION_ORDER 2, each on triangles and on quads
  lts          LTS_TIERS 1 to 8 on a graded mesh (cell sizes doubling across the mesh)
  bc           every boundary type (NORMAL_FLOW with a falling and a rising slope,
               SPECIFIED_STAGE, TS_STAGE, SPECIFIED_FLOW inflow and outflow, TS_FLOW,
               RATING_CURVE, WALL_DRAG) under each momentum equation, VFR_FACE stage edges
  closure      CELL_CLOSURE VFR, FACE_RECONSTRUCTION VFR_FACE, both, on triangles and quads
  fronts       a dam break onto a dry bed with FRONT_REBUILD AUTO/YES/NO, H_MOVE 0 and 0.05
  froude       a steep bed with FROUDE_MAX 0.5 and 3
  rain         rain on a dry mesh under every RAINFALL_MODE, with two located gages
  infil        each 2D infiltration method, a per-triangle override, INFIL_STEP
  evap         EVAPORATION NO/YES/CLIMATE over a ponded mesh
  momentum     THETA, THETA_REFERENCE_STEP, ADVECTION
  physics      Smagorinsky, mixing length, Coriolis and wall drag (FULL_SWE, LTS_TIERS 1)
  misc         THREADS 2 (the per-thread evaporation ledger), COUPLING_SYNC batching,
               edge conveyance (leaky and closed), initial velocity, US units, KINWAVE and
               STEADY 1D routing, SKIP_STEADY_STATE, IGNORE_ROUTING

Both reference builds read them (the 1D build skips the [2D_*] sections with a warning).
Run from anywhere: `python3 gate/twods_gen.py`.

Written for swmm6-rust, 12 November 2026, by Claude (Anthropic) for Robert Dickinson. Not an
OpenSWMM file; the deck format is OpenSWMM 6's (HydroCouple/openswmm.engine, swmm6_rel @ 88329d6,
Apache License 2.0).
"""
import math
import os

H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(H, 'gate', 'decks', 'twods')

HEADER = (';; swmm6-rust gate deck {name}: {what}\n'
          ';; Generated by gate/twods_gen.py for the 2D step gate. Not an OpenSWMM file.\n\n')


class Mesh:
    """A structured nx x ny mesh over [0, W] x [0, Hy]; cells are triangle pairs (diagonal
    a-c of each square), quads, or quads in the west half and triangles in the east half."""

    def __init__(self, nx=6, ny=4, W=60.0, Hy=40.0, kind='tri', grade=1.0, z0=10.0, sx=-0.01,
                 sy=0.0, bump=0.3, n=0.03, init=None):
        self.nx, self.ny, self.kind = nx, ny, kind
        # x nodes, possibly graded (each column `grade` times as wide as the previous)
        w = [grade ** i for i in range(nx)]
        s = sum(w)
        xs = [0.0]
        for wi in w:
            xs.append(xs[-1] + W * wi / s)
        ys = [Hy * j / ny for j in range(ny + 1)]
        self.xs, self.ys = xs, ys
        self.verts = []
        for j in range(ny + 1):
            for i in range(nx + 1):
                x, y = xs[i], ys[j]
                r2 = (x - 0.6 * W) ** 2 + (y - 0.5 * Hy) ** 2
                z = z0 + sx * x + sy * y + bump * math.exp(-r2 / (0.04 * W * W))
                self.verts.append((x, y, z))
        self.tris, self.quads = [], []
        # cell id per square: ('tri', lower, upper) or ('quad', q)
        self.square = {}
        sq_tri, sq_quad = [], []
        for j in range(ny):
            for i in range(nx):
                quad = kind == 'quad' or (kind == 'mixed' and i < nx // 2)
                (sq_quad if quad else sq_tri).append((i, j))
        for (i, j) in sq_tri:
            a, b, c, d = self.v(i, j), self.v(i + 1, j), self.v(i + 1, j + 1), self.v(i, j + 1)
            h0 = init(i, j) if init else 0.0
            self.square[(i, j)] = ('tri', len(self.tris), len(self.tris) + 1)
            self.tris.append((a, b, c, n, h0))
            self.tris.append((a, c, d, n, h0))
        nt = len(self.tris)
        for (i, j) in sq_quad:
            a, b, c, d = self.v(i, j), self.v(i + 1, j), self.v(i + 1, j + 1), self.v(i, j + 1)
            h0 = init(i, j) if init else 0.0
            self.square[(i, j)] = ('quad', nt + len(self.quads))
            self.quads.append((a, b, c, d, n, h0))

    def v(self, i, j):
        return j * (self.nx + 1) + i

    def n_cells(self):
        return len(self.tris) + len(self.quads)

    def edge(self, side, i, j):
        """(cell, local edge) of the boundary edge on `side` (W, E, S, N) of square (i, j)."""
        sq = self.square[(i, j)]
        if sq[0] == 'tri':
            lower, upper = sq[1], sq[2]
            # lower (a, b, c): e0 = (b, c) east, e2 = (a, b) south;
            # upper (a, c, d): e0 = (c, d) north, e1 = (d, a) west
            return {'E': (lower, 0), 'S': (lower, 2), 'N': (upper, 0), 'W': (upper, 1)}[side]
        q = sq[1]
        # quad (a, b, c, d): e0 = (b, c) east, e1 = (c, d) north, e2 = (d, a) west, e3 = (a, b) south
        return {'E': (q, 0), 'N': (q, 1), 'W': (q, 2), 'S': (q, 3)}[side]

    def side_edges(self, side):
        if side in ('W', 'E'):
            i = 0 if side == 'W' else self.nx - 1
            return [self.edge(side, i, j) for j in range(self.ny)]
        j = 0 if side == 'S' else self.ny - 1
        return [self.edge(side, i, j) for i in range(self.nx)]

    def text(self):
        t = '[2D_VERTICES]\n;;X  Y  Z\n'
        for (x, y, z) in self.verts:
            t += '%.6f  %.6f  %.6f\n' % (x, y, z)
        t += '\n'
        if self.tris:
            t += '[2D_TRIANGLES]\n;;V1  V2  V3  MANNINGS_N  INIT_DEPTH  TAG\n'
            for k, (a, b, c, n, h0) in enumerate(self.tris):
                t += '%d  %d  %d  %.4f  %.4f  %s\n' % (a, b, c, n, h0, 'LAWN' if k % 3 else 'PAVED')
            t += '\n'
        if self.quads:
            t += '[2D_QUADS]\n;;V1  V2  V3  V4  N  INIT_DEPTH  TAG\n'
            for k, (a, b, c, d, n, h0) in enumerate(self.quads):
                t += '%d  %d  %d  %d  %.4f  %.4f  %s\n' % (a, b, c, d, n, h0, 'LAWN' if k % 3 else 'PAVED')
            t += '\n'
        return t


def deck(name, what, opts2d=(), mesh=None, bcs=(), units='CMS', routing='DYNWAVE', rain=20.0,
         rain_minutes=30, hours=2, routing_step=10, report='00:05:00', extra_options=(),
         evaporation=None, extra='', gages=1, symbols=False, sections2d=''):
    if mesh is None:
        mesh = Mesh()
    t = HEADER.format(name=name, what=what)
    t += '[OPTIONS]\nFLOW_UNITS           %s\nFLOW_ROUTING         %s\n' % (units, routing)
    t += 'START_DATE           01/01/2026\nSTART_TIME           00:00:00\n'
    t += 'END_DATE             01/01/2026\nEND_TIME             %02d:00:00\n' % hours
    t += 'REPORT_STEP          %s\nWET_STEP             00:05:00\nDRY_STEP             00:05:00\n' % report
    t += 'ROUTING_STEP         %s\nALLOW_PONDING        NO\n' % routing_step
    for k, v in extra_options:
        t += '%-20s %s\n' % (k, v)
    t += '\n'
    if evaporation is not None:
        t += '[EVAPORATION]\nCONSTANT             %s\nDRY_ONLY             NO\n\n' % evaporation
    t += '[RAINGAGES]\n;;Name  Format  Interval  SCF  Source\n'
    for g in range(gages):
        t += 'RG%d     INTENSITY 0:05  1.0  TIMESERIES  RAIN%d_TS\n' % (g + 1, g + 1)
    t += '\n'
    t += ('[JUNCTIONS]\n;;Name  Elev  MaxDepth  InitDepth  SurDepth  Aponded\n'
          'J1      0.0   1.0       0          0         0\n\n'
          '[OUTFALLS]\n;;Name  Elev   Type  Gated\nO1     -0.5    FREE  NO\n\n'
          '[CONDUITS]\n;;Name  From  To  Length  Roughness  InOffset  OutOffset  InitFlow\n'
          'C1      J1    O1  30.0    0.013      0         0          0\n\n'
          '[XSECTIONS]\n;;Link  Shape  Geom1  Geom2  Geom3  Geom4  Barrels\n'
          'C1      CIRCULAR  0.3  0  0  0  1\n\n'
          '[INFLOWS]\n;;Node  Constituent  Time Series  Type  Mfactor  Sfactor  Baseline  Pattern\n'
          'J1      FLOW         J1_TS        FLOW  1.0      1.0\n\n')
    t += '[TIMESERIES]\n'
    for g in range(gages):
        r = rain if g == 0 else rain * 0.4
        t += 'RAIN%d_TS  01/01/2026  00:00  %.3f\n' % (g + 1, r)
        t += 'RAIN%d_TS              00:%02d  %.3f\n' % (g + 1, rain_minutes, 0.0)
        t += 'RAIN%d_TS              %02d:00  0.0\n' % (g + 1, hours)
    t += 'J1_TS  01/01/2026  00:00  0.02\nJ1_TS              %02d:00  0.02\n' % hours
    t += ('STAGE_TS  01/01/2026  00:00  %.3f\nSTAGE_TS              01:00  %.3f\nSTAGE_TS              %02d:00  %.3f\n'
          % (mesh.verts[0][2] + 0.10, mesh.verts[0][2] + 0.40, hours, mesh.verts[0][2] + 0.05))
    t += ('FLOW_TS  01/01/2026  00:00  -0.010\nFLOW_TS              00:40  -0.060\nFLOW_TS              01:20  0.020\n'
          'FLOW_TS              %02d:00  0.0\n' % hours)
    t += '\n'
    zr = min(z for (_, _, z) in mesh.verts)
    t += ('[CURVES]\n;;Name  Type  X  Y\nDOWN_RC  RATING  %.3f  0.0\nDOWN_RC          %.3f  0.02\n'
          'DOWN_RC          %.3f  0.15\nDOWN_RC          %.3f  0.60\n\n' % (zr - 1.0, zr + 0.05, zr + 0.3, zr + 1.0))
    if symbols:
        t += '[SYMBOLS]\n;;Gage  X  Y\nRG1  5.0  35.0\n'
        if gages > 1:
            t += 'RG2  55.0  5.0\n'
        t += '\n'
    t += extra
    t += '[COORDINATES]\nJ1  100.0  100.0\nO1  130.0  100.0\n\n'
    t += '[2D_OPTIONS]\nMAX_TIMESTEP  10\nDRY_DEPTH  0.001\nREPORT_2D  YES\n'
    for k, v in opts2d:
        t += '%s  %s\n' % (k, v)
    t += '\n'
    t += mesh.text()
    if bcs:
        t += '[2D_BOUNDARY_CONDITIONS]\n;;TRI  EDGE  TYPE  PARAM_1  PARAM_2  GROUP\n'
        for (cell, e, ty, p1) in bcs:
            t += '%d  %d  %s  %s  *  *\n' % (cell, e, ty, p1)
        t += '\n'
    t += sections2d
    p = os.path.join(OUT, name + '.inp')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(t)


def bc_side(mesh, side, ty, p1):
    return [(c, e, ty, p1) for (c, e) in mesh.side_edges(side)]


INFIL = {
    'horton': '* HORTON 76.2 10.16 4 0.1 254.0 LOST',
    'modified_horton': '* MODIFIED_HORTON 76.2 10.16 4 0.1 254.0 LOST',
    'green_ampt': '* GREEN_AMPT 101.6 12.7 0.3 0 0 LOST',
    'modified_green_ampt': '* MODIFIED_GREEN_AMPT 101.6 12.7 0.3 0 0 LOST',
    'curve_number': '* CURVE_NUMBER 75 0 0.5 0 0 LOST',
    'constant': '* CONSTANT 12.7 0 0 0 0 LOST',
}

MOMENTUM = [
    ('li', []),
    ('dw', [('MOMENTUM_EQUATION', 'DIFFUSIVE_WAVE')]),
    ('swe', [('MOMENTUM_EQUATION', 'FULL_SWE')]),
    ('swe1', [('MOMENTUM_EQUATION', 'FULL_SWE'), ('LTS_TIERS', '1')]),
    ('swe2', [('MOMENTUM_EQUATION', 'FULL_SWE'), ('LTS_TIERS', '1'), ('RECONSTRUCTION_ORDER', '2')]),
]


def dam(i, j):
    return 0.4 if i < 2 else 0.0


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.inp'):
            os.remove(os.path.join(OUT, f))
    n = 0

    def w(*a, **k):
        nonlocal n
        deck(*a, **k)
        n += 1

    # momentum closures on triangles, quads and a mixed mesh, with a dam break and an outlet
    for kind in ('tri', 'quad', 'mixed'):
        for mname, mo in MOMENTUM:
            m = Mesh(kind=kind, init=dam)
            bcs = bc_side(m, 'E', 'NORMAL_FLOW', '0.005')
            w('mom_%s_%s' % (mname, kind), 'dam break on a %s mesh; %s' % (kind, ', '.join('%s %s' % x for x in mo) or 'LOCAL_INERTIAL'),
              mo, m, bcs)
    # LTS tiers on a graded mesh (each column twice the previous)
    for k in range(1, 9):
        m = Mesh(nx=9, ny=2, W=300.0, Hy=10.0, grade=2.0, init=lambda i, j: 0.3 if i < 3 else 0.05)
        w('lts%d' % k, 'graded mesh (cell widths doubling), LTS_TIERS %d' % k, [('LTS_TIERS', str(k))], m,
          bc_side(m, 'E', 'NORMAL_FLOW', '0.002'))
    for mname, mo in MOMENTUM[1:3]:
        m = Mesh(nx=9, ny=2, W=300.0, Hy=10.0, grade=2.0, init=lambda i, j: 0.3 if i < 3 else 0.05)
        w('lts8_%s' % mname, 'graded mesh, LTS_TIERS 8; %s' % ', '.join('%s %s' % x for x in mo), [('LTS_TIERS', '8')] + mo, m,
          bc_side(m, 'E', 'NORMAL_FLOW', '0.002'))
    # every boundary type under each momentum equation
    BCS = [
        ('nf_out', 'NORMAL_FLOW', '0.01'),
        ('nf_in', 'NORMAL_FLOW', '-0.01'),
        ('stage', 'SPECIFIED_STAGE', None),
        ('ts_stage', 'TS_STAGE', 'STAGE_TS'),
        ('flow_in', 'SPECIFIED_FLOW', '-0.05'),
        ('flow_out', 'SPECIFIED_FLOW', '0.02'),
        ('ts_flow', 'TS_FLOW', 'FLOW_TS'),
        ('rating', 'RATING_CURVE', 'DOWN_RC'),
    ]
    for mname, mo in MOMENTUM:
        for bname, ty, p1 in BCS:
            m = Mesh(kind='tri', init=lambda i, j: 0.15 if i < 3 else 0.0)
            if p1 is None:
                p1 = '%.3f' % (m.verts[m.v(0, 0)][2] + 0.35)
            side = 'W' if bname in ('flow_in', 'nf_in', 'stage', 'ts_stage', 'ts_flow') else 'E'
            bcs = bc_side(m, side, ty, p1)
            w('bc_%s_%s' % (bname, mname), '%s edges on the %s side; %s' % (ty, side, ', '.join('%s %s' % x for x in mo) or 'LOCAL_INERTIAL'),
              mo, m, bcs)
    # boundary types on quads and with VFR_FACE
    for bname, ty, p1 in BCS:
        m = Mesh(kind='quad', init=lambda i, j: 0.15 if i < 3 else 0.0)
        if p1 is None:
            p1 = '%.3f' % (m.verts[m.v(0, 0)][2] + 0.35)
        side = 'W' if bname in ('flow_in', 'nf_in', 'stage', 'ts_stage', 'ts_flow') else 'E'
        w('bcq_%s' % bname, '%s edges on a quad mesh' % ty, [], m, bc_side(m, side, ty, p1))
        m = Mesh(kind='tri', init=lambda i, j: 0.15 if i < 3 else 0.0)
        w('bcv_%s' % bname, '%s edges, CELL_CLOSURE VFR and FACE_RECONSTRUCTION VFR_FACE' % ty,
          [('CELL_CLOSURE', 'VFR'), ('FACE_RECONSTRUCTION', 'VFR_FACE')], m, bc_side(m, side, ty, p1))
    # closures
    for kind in ('tri', 'quad', 'mixed'):
        for cname, co in [('vfr', [('CELL_CLOSURE', 'VFR')]), ('vfrface', [('FACE_RECONSTRUCTION', 'VFR_FACE')]),
                          ('vfrboth', [('CELL_CLOSURE', 'VFR'), ('FACE_RECONSTRUCTION', 'VFR_FACE')])]:
            for mname, mo in (MOMENTUM[0], MOMENTUM[1], MOMENTUM[2]):
                m = Mesh(kind=kind, bump=0.6, init=dam)
                w('cl_%s_%s_%s' % (cname, kind, mname), '%s on a %s mesh; %s' % (cname, kind, mname), co + mo, m,
                  bc_side(m, 'E', 'NORMAL_FLOW', '0.005'))
    # wet/dry fronts
    for fname, fo in [('auto', []), ('yes', [('FRONT_REBUILD', 'YES')]), ('no', [('FRONT_REBUILD', 'NO')]),
                      ('hmove0', [('H_MOVE', '0')]), ('hmove05', [('H_MOVE', '0.05')])]:
        for mname, mo in (MOMENTUM[0], MOMENTUM[2]):
            m = Mesh(nx=10, ny=4, W=100.0, sx=0.0, bump=0.0, init=lambda i, j: 0.5 if i < 3 else 0.0)
            w('front_%s_%s' % (fname, mname), 'dam break onto a dry flat bed; %s; %s' % (fname, mname), fo + mo, m)
    # high Froude
    for fr in ('0.5', '3'):
        for mname, mo in (MOMENTUM[0], MOMENTUM[1]):
            m = Mesh(sx=-0.08, init=lambda i, j: 0.2 if i == 0 else 0.0)
            w('froude%s_%s' % (fr.replace('.', ''), mname), 'steep bed, FROUDE_MAX %s; %s' % (fr, mname), [('FROUDE_MAX', fr)] + mo, m,
              bc_side(m, 'E', 'NORMAL_FLOW', '0.08'))
    # rain on a dry mesh under every RAINFALL_MODE, two located gages
    for mode in ('NATURAL_NEIGHBOUR', 'NEAREST_NEIGHBOUR', 'SYSTEM', 'NONE'):
        m = Mesh()
        w('rain_%s' % mode.lower(), 'rain on a dry mesh, two located gages, RAINFALL_MODE %s' % mode,
          [('RAINFALL_MODE', mode)], m, bc_side(m, 'E', 'NORMAL_FLOW', '0.005'), rain=60.0, gages=2, symbols=True)
    m = Mesh()
    w('rain_long', 'rain on a dry mesh for 90 minutes (rate changes inside batches)', [], m, bc_side(m, 'E', 'NORMAL_FLOW', '0.005'),
      rain=40.0, rain_minutes=55, routing_step='7')
    m = Mesh(kind='quad')
    w('rain_quad_dw', 'rain on a dry quad mesh, DIFFUSIVE_WAVE', [('MOMENTUM_EQUATION', 'DIFFUSIVE_WAVE')], m,
      bc_side(m, 'E', 'NORMAL_FLOW', '0.005'), rain=60.0)
    # infiltration
    for iname, row in INFIL.items():
        m = Mesh()
        w('infil_%s' % iname, 'rain on the mesh with %s infiltration' % iname.upper(), [('INFILTRATION', 'YES')], m,
          bc_side(m, 'E', 'NORMAL_FLOW', '0.005'), rain=50.0, sections2d='[2D_INFILTRATION_DEFAULTS]\n%s\n\n' % row)
    m = Mesh()
    w('infil_override', 'HORTON defaults with GREEN_AMPT and CONSTANT per-triangle overrides, INFIL_STEP 60',
      [('INFILTRATION', 'YES'), ('INFIL_STEP', '60')], m, bc_side(m, 'E', 'NORMAL_FLOW', '0.005'), rain=50.0,
      sections2d='[2D_INFILTRATION_DEFAULTS]\n%s\n\n[2D_INFILTRATION]\n1 GREEN_AMPT 101.6 12.7 0.3 0 0 LOST\n6 CONSTANT 25 0 0 0 0 LOST\n\n' % INFIL['horton'])
    m = Mesh(init=lambda i, j: 0.05)
    w('infil_swe', 'GREEN_AMPT infiltration under FULL_SWE', [('INFILTRATION', 'YES')] + MOMENTUM[2][1], m,
      bc_side(m, 'E', 'NORMAL_FLOW', '0.005'), rain=30.0, sections2d='[2D_INFILTRATION_DEFAULTS]\n%s\n\n' % INFIL['green_ampt'])
    m = Mesh(init=lambda i, j: 0.05)
    w('infil_swe2', 'CURVE_NUMBER infiltration under FULL_SWE, RECONSTRUCTION_ORDER 2', [('INFILTRATION', 'YES')] + MOMENTUM[4][1], m,
      bc_side(m, 'E', 'NORMAL_FLOW', '0.005'), rain=30.0, sections2d='[2D_INFILTRATION_DEFAULTS]\n%s\n\n' % INFIL['curve_number'])
    # evaporation
    for ename, ev in (('no', 'NO'), ('yes', 'YES'), ('climate', 'CLIMATE')):
        for mname, mo in (MOMENTUM[0], MOMENTUM[4]):
            m = Mesh(sx=0.0, bump=0.0, init=lambda i, j: 0.002 + 0.0005 * i)
            w('evap_%s_%s' % (ename, mname), 'a thin ponded film, project evaporation 50 mm/day, EVAPORATION %s; %s' % (ev, mname),
              [('EVAPORATION', ev)] + mo, m, rain=0.0, evaporation='50.0')
    # momentum options
    for oname, oo in [('theta1', [('THETA', '1.0')]), ('theta05', [('THETA', '0.5')]), ('thetaref', [('THETA_REFERENCE_STEP', '2')]),
                      ('advection', [('ADVECTION', 'YES')]), ('advection_theta', [('ADVECTION', 'YES'), ('THETA', '0.6')]),
                      ('cfl03', [('CFL_NUMBER', '0.3')]), ('maxdt1', [('MAX_TIMESTEP', '1')]), ('fluxeps_dw', [('FLUX_DH_EPS', '0.02'), ('MOMENTUM_EQUATION', 'DIFFUSIVE_WAVE')])]:
        m = Mesh(init=dam)
        w('opt_%s' % oname, 'dam break, %s' % ', '.join('%s %s' % x for x in oo), oo, m, bc_side(m, 'E', 'NORMAL_FLOW', '0.005'))
    # optional momentum physics (FULL_SWE, LTS_TIERS 1, uncoupled)
    SWE1 = [('MOMENTUM_EQUATION', 'FULL_SWE'), ('LTS_TIERS', '1')]
    for pname, po in [('smag', [('TURBULENCE_MODEL', 'SMAGORINSKY')]),
                      ('smag_cs', [('TURBULENCE_MODEL', 'SMAGORINSKY'), ('SMAGORINSKY_CS', '0.3'), ('EDDY_VISCOSITY_BACKGROUND', '0.05')]),
                      ('mixing', [('TURBULENCE_MODEL', 'MIXING_LENGTH')]),
                      ('mixing_c', [('TURBULENCE_MODEL', 'MIXING_LENGTH'), ('MIXING_LENGTH_COEFFICIENT', '0.2'), ('EDDY_VISCOSITY_BACKGROUND', '0.01')]),
                      ('coriolis', [('CORIOLIS', 'LATITUDE'), ('CORIOLIS_LATITUDE', '45')]),
                      ('coriolis_f', [('CORIOLIS', 'CONSTANT_F'), ('CORIOLIS_F', '2.0e-3')]),
                      ('smag_o2', [('TURBULENCE_MODEL', 'SMAGORINSKY'), ('RECONSTRUCTION_ORDER', '2')])]:
        m = Mesh(sx=0.0, init=dam)
