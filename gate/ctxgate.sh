#!/bin/bash
# The state gates: run every corpus deck, upstream test deck and gate/decks deck through
# upstream (the reference library, gate/diff/*) and through the translation
# (target/release/examples/*), dump the state, compare stdout and exit code. Build both
# sides first with gate/build.sh.
#
#   gate/ctxgate.sh [TAGS|ALL] [resolve]
#       parse: upstream's InputReader + handlers (gate/diff/ctxread) against examples/ctxread;
#       TAGS is a comma-separated list of sections or ALL. "resolve": both sides run
#       resolve_cross_references after reading.
#   gate/ctxgate.sh open [lenient|metadata]
#       the whole SWMMEngine::open (swmm_engine_open in gate/diff/ctxopen, examples/ctxopen),
#       then the context and the engine members open() sets; open_rc too. "lenient" sets
#       swmm_engine_set_lenient_open first; "metadata" opens through swmm_engine_open_metadata.
#   gate/ctxgate.sh inithyd
#       open, then SWMMEngine::initHydraulics (gate/diff/inithyd, examples/inithyd); dumps the
#       context, the open() members and the Router, controls, inflow, RDII, exfiltration,
#       inlet, structure and interface-file solvers (rtdump).
#   gate/ctxgate.sh inithydro [open|lenient|rdii]
#       open, then SWMMEngine::initHydrology (gate/diff/inithydro, examples/inithydro); dumps
#       the context, the open() members and the hydrology solver members (hydrodump).
#       "rdii" runs rdii_.init first, as initHydraulics does.
#   gate/ctxgate.sh initqual quality|geometry|massbal
#       open, then one of SWMMEngine::initQuality / initGeometry / initMassBalance
#       (gate/diff/initqual, examples/initqual); dumps the context, the open() members and the
#       quality members. massbal first runs
#       `initqual deck massref side` (upstream's own initialize, in its own process) for the
#       hydrology solver state initMassBalance reads; see gate/diff/initqual.cpp.
#   gate/ctxgate.sh loadrt [open|lenient|metadata|init]
#       the context loader (examples/common/ctxload.rs, generated by tools/ctxload.py). Per deck:
#         rust:  examples/ctxopen dump -> examples/ctxload (load into a fresh engine, dump
#                again) -> cmp
#         cross: gate/diff/ctxopen (upstream) dump -> examples/ctxload -> cmp with upstream's text
#       "init" dumps after initialize too (the translation's SwmmEngine::initialize on the
#       rust side). A deck where a harness aborts (no dump: the U1/U57 decks, on both sides)
#       is counted apart.
#
#   gate/ctxgate.sh init | start
#       the run lifecycle (gate/diff/ctxstep, examples/ctxstep): open, SWMMEngine::initialize
#       (and SWMMEngine::start(1) for "start"), then the whole state: the context, the open()
#       members, the router and hydraulic solvers, the hydrology solvers, the quality members
#       and the lifecycle members (lifedump). Files a deck SAVEs to ([FILES], gate/savefiles.py)
#       are backed up before each side runs and restored after, since start() truncates them.
#   gate/ctxgate.sh step [N]
#       the same, then up to N routing steps (default 1) through SWMMEngine::step, the dump of
#       each step hashed (FNV-1a 64). A deck counts as identical when both sides print the same
#       (both ran N steps, or to the end, or stopped on the same error); as "stub" when the
#       translation stopped at a call into code not translated yet ("stub <phase> <what>", its
#       last line) with everything before it identical; otherwise it differs, and with
#       CTXGATE_DIFFDIR=dir the first differing deck's full dumps at the first differing step
#       are written there (c.txt, r.txt).
#   gate/ctxgate.sh helpers [K]
#       step()'s own helpers against upstream's on a real mid-run state: upstream runs K real
#       steps (default 10), writes its context and the engine members the helpers read, and
#       calls each helper (updateStatistics, updateRoutingMassBalance, computeFinalStorage,
#       computeFinalQualityMassBalance, accumulateNodeRoutingTotals, checkRoutingDiverged,
#       isBetweenEvents/isInSteadyState, assembleLateralInflows, resetStepMassBalance +
#       applyForcings) on that state; the translation loads the same state into its own
#       started engine and calls its translation. The context after each helper is compared
#       (hashed). Decks a helper does not apply to print "skipped" on both sides.
#   gate/ctxgate.sh route [K1 [K0 [hyd]]]
#       the routing-step cross test (default calls 1..300). Per deck, upstream
#       (gate/diff/routestep) is opened, initialized and started through its C API and stepped
#       with swmm_engine_step; the harness's own SWMMEngine::stepRouting (the library calls it
#       through its PLT) dumps the whole state before and after the library's stepRouting for
#       calls K0..K1 (context, rtdump, qualdump, stepdump). examples/routestep then, for each
#       call, opens the deck, runs the translated init legs, loads upstream's BEFORE dump
#       (ctxload: load, load_rt, load_qual), runs the translated step_routing with upstream's
#       dt and dumps, comparing as it goes (upstream's output is piped in, never written to
#       disk): first the loader's round trip (load, dump, cmp with the BEFORE block), then the
#       AFTER block; it stops at the first difference. Results: identical N, differ (first
#       call, label, element), loaddiff, nottranslated (the translation stops on a path it
#       does not translate yet), nostart (upstream's open/initialize/start failed), nosteps,
#       panic, noresult. (examples/routestep deck file [step|load] and gate/routecmp.py
#       compare saved streams by hand.)
#       "hyd" runs each dumped call with options.ignore_quality set on both sides (the
#       hydraulic step of a deck with pollutants, while quality routing is not translated).
#       CTXGATE_LOG=file appends one line per deck. Files a deck SAVEs to (gate/savefiles.py)
#       are backed up before the run and restored after, since upstream's start() truncates
#       them and another deck may USE them.
#   gate/ctxgate.sh out start
#       the output side after start() (gate/diff/outgate and examples/outgate, "start"): both
#       run open, initialize and start(save = 1) as the CLI does, writing a .rpt and a .out
#       into a scratch folder, and stop there (on success the files are flushed and the
#       process ends without closing them; a failure takes the CLI's failure path: close,
#       destroy). The two .rpt files (without the three wall-clock lines), the two .out files
#       and the exit codes must be identical: the preamble and the .out header after a start,
#       the whole report of a deck that fails in open, initialize or start.
#   gate/ctxgate.sh out run [K0 [K1 [STRIDE]]]
#       the period records and the end of the run without the runoff step: upstream
#       (gate/diff/outgate run) runs the deck to the end through its C API, printing the whole
#       state before each report period's postOutputSnapshot (periods K0..K1, default all,
#       every STRIDE-th) and before end(); examples/outgate stream loads each state into its
#       own started engine, runs the translated post_output_snapshot, then end, report and
#       close, and compares the period records, the .out header and closing records, the
#       .rpt (clock lines removed) and the exit code. Results: identical P, differ (what,
#       where), nottranslated, nostart (upstream stops before stepping; files compared as in
#       "start"), noresult, panic. Files a deck SAVEs to are backed up and restored.
#
# DECKLIST=file runs the decks listed in it (one path per line) instead of the default set.
# CTXGATE_EXAMPLES=dir runs the Rust harnesses from dir (default target/release/examples), so a
# gate can run while the next build goes to another CARGO_TARGET_DIR.
# CTXGATE_KEEP=file keeps the list of differing decks; CTXGATE_SHOW=n shows the first n.
H=$(cd "$(dirname "$0")/.." && pwd); W=$(mktemp -d)
E="${CTXGATE_EXAMPLES:-$H/target/release/examples}"   # CTXGATE_EXAMPLES=dir: the Rust harnesses built elsewhere (CARGO_TARGET_DIR)
if [ -n "$DECKLIST" ]; then sort "$DECKLIST" > "$W/decks.txt"      # DECKLIST=file: one deck path per line
else { find /root/work/corpus -name '*.inp'; find /root/work/swmm6src/upstream/tests -name '*.inp'; find "$H/gate/decks" -name '*.inp'; } | sort > "$W/decks.txt"; fi

if [ "${1:-}" = route ]; then
  K1=${2:-300}; K0=${3:-1}; HYD=${4:-}; C_BIN="$H/gate/diff/routestep"; R_BIN="$E/routestep"
  : > "$W/res.txt"
  mkdir -p "$W/bak"
  while IFS= read -r d; do
    # back up the files the deck SAVEs to; restore them after the run
    python3 "$H/gate/savefiles.py" "$d" > "$W/saves.txt" 2>/dev/null; k=0
    while IFS= read -r f; do k=$((k+1)); rm -f "$W/bak/$k"; [ -f "$f" ] && cp -p "$f" "$W/bak/$k"; done < "$W/saves.txt"
    # upstream's dumps are piped straight into the translation (no file: a big deck's 300
    # dumped calls run to gigabytes); examples/routestep stream prints one result line
    ( cd "$(dirname "$d")" && timeout 3600 "$C_BIN" "$d" "$K0" "$K1" $HYD 2>/dev/null | timeout 3600 "$R_BIN" "$d" stream > "$W/r.txt" 2> "$W/err.txt" ) 2>/dev/null
    k=0; while IFS= read -r f; do k=$((k+1)); if [ -f "$W/bak/$k" ]; then cp -p "$W/bak/$k" "$f"; else rm -f "$f"; fi; done < "$W/saves.txt"
    res=$(head -1 "$W/r.txt")
    if grep -q panicked "$W/err.txt"; then res="panic $(grep -m1 -A1 panicked "$W/err.txt" | tail -1 | head -c 160)"
    elif [ -z "$res" ]; then res="noresult"; fi
    echo "$res $d" >> "$W/res.txt"
    [ -n "$CTXGATE_LOG" ] && echo "$res $d" >> "$CTXGATE_LOG"
  done < "$W/decks.txt"
  for k in identical differ loaddiff nottranslated nostart nosteps panic noresult; do
    printf '%s %s\n' "$k" "$(grep -c "^$k " "$W/res.txt")"
  done | tr '\n' ' '; echo "(route calls $K0..$K1 $HYD)"
  grep -v '^identical \|^nostart \|^nosteps ' "$W/res.txt" | head -${CTXGATE_SHOW:-5}
  [ -n "$CTXGATE_KEEP" ] && cp "$W/res.txt" "$CTXGATE_KEEP"; rm -rf "$W"
  exit 0
fi

if [ "${1:-}" = out ]; then
  M=${2:-start}; C_BIN="$H/gate/diff/outgate"; R_BIN="$E/outgate"; K0=${3:-1}; K1=${4:-0}; ST=${5:-1}
  : > "$W/res.txt"; mkdir -p "$W/bak" "$W/c" "$W/r"
  while IFS= read -r d; do
    python3 "$H/gate/savefiles.py" "$d" > "$W/saves.txt" 2>/dev/null; k=0
    while IFS= read -r f; do k=$((k+1)); rm -f "$W/bak/$k"; [ -f "$f" ] && cp -p "$f" "$W/bak/$k"; done < "$W/saves.txt"
    restore() { local k=0; while IFS= read -r f; do k=$((k+1)); if [ -f "$W/bak/$k" ]; then cp -p "$W/bak/$k" "$f"; else rm -f "$f"; fi; done < "$W/saves.txt"; }
    rm -f "$W"/c/* "$W"/r/*
    if [ "$M" = start ]; then
      ( cd "$(dirname "$d")" && timeout 600 "$C_BIN" "$d" "$W/c/r.rpt" "$W/c/r.out" start > "$W/c.txt" 2>/dev/null; echo "exit $?" >> "$W/c.txt" ) 2>/dev/null; restore
      ( cd "$(dirname "$d")" && timeout 600 "$R_BIN" "$d" "$W/r/r.rpt" "$W/r/r.out" start > "$W/r.txt" 2> "$W/err.txt"; echo "exit $?" >> "$W/r.txt" ) 2>/dev/null; restore
      res=identical
      if grep -q "^nottranslated" "$W/r.txt"; then res="$(head -1 "$W/r.txt" | head -c 160)"
      elif grep -q "STUB\|not translated" "$W/err.txt"; then res="nottranslated $(grep -m1 -o 'STUB.*' "$W/err.txt" | head -c 120)"
      elif grep -q panicked "$W/err.txt"; then res="panic $(grep -m1 -A1 panicked "$W/err.txt" | tail -1 | head -c 160)"
      elif ! cmp -s "$W/c.txt" "$W/r.txt"; then res="differ rc $(tr '\n' ' ' < "$W/c.txt") / $(tr '\n' ' ' < "$W/r.txt")"
      elif ! cmp -s <(grep -av 'Analysis begun\|Analysis ended\|Total elapsed time' "$W/c/r.rpt" 2>/dev/null) <(grep -av 'Analysis begun\|Analysis ended\|Total elapsed time' "$W/r/r.rpt" 2>/dev/null); then
        res="differ rpt $(diff <(grep -av 'Analysis begun\|Analysis ended\|Total elapsed time' "$W/c/r.rpt" 2>/dev/null) <(grep -av 'Analysis begun\|Analysis ended\|Total elapsed time' "$W/r/r.rpt" 2>/dev/null) | head -3 | tr '\n' '|' | head -c 200)"
      elif [ -f "$W/c/r.out" ] || [ -f "$W/r/r.out" ]; then
        if ! cmp -s "$W/c/r.out" "$W/r/r.out"; then res="differ out $(cmp "$W/c/r.out" "$W/r/r.out" 2>&1 | head -1)"; fi
      fi
      [ "$res" = identical ] && res="identical $(head -1 "$W/c.txt")"
    else
      ( cd "$(dirname "$d")" && timeout 3600 "$C_BIN" "$d" "$W/c/r.rpt" "$W/c/r.out" run "$K0" "$K1" "$ST" 2>/dev/null | timeout 3600 "$R_BIN" "$d" "$W/r/r.rpt" "$W/r/r.out" stream "$W/c/r.rpt" "$W/c/r.out" > "$W/r.txt" 2> "$W/err.txt" ) 2>/dev/null
      restore
      res=$(head -1 "$W/r.txt")
      if grep -q panicked "$W/err.txt"; then res="panic $(grep -m1 -A1 panicked "$W/err.txt" | tail -1 | head -c 160)"
      elif [ -z "$res" ]; then res="noresult"; fi
    fi
    echo "$res $d" >> "$W/res.txt"
    [ -n "$CTXGATE_LOG" ] && echo "$res $d" >> "$CTXGATE_LOG"
  done < "$W/decks.txt"
  for k in identical differ nottranslated nostart panic noresult; do
    printf '%s %s\n' "$k" "$(grep -c "^$k " "$W/res.txt")"
  done | tr '\n' ' '; echo "(out $M $K0..$K1/$ST)"
  grep -v '^identical \|^nostart ' "$W/res.txt" | head -${CTXGATE_SHOW:-5}
  [ -n "$CTXGATE_KEEP" ] && cp "$W/res.txt" "$CTXGATE_KEEP"; rm -rf "$W"
  exit 0
fi

if [ "${1:-}" = loadrt ]; then
  M=${2:-open}; C_BIN="$H/gate/diff/ctxopen"; R_BIN="$E/ctxopen"; L_BIN="$E/ctxload"
  rs=0; rd=0; rn=0; xs=0; xd=0; xn=0; : > "$W/differ.txt"
  while IFS= read -r d; do
    cd "$(dirname "$d")" || continue
    if ( timeout 120 "$R_BIN" "$d" "$M" > "$W/a.txt"; rc=$?; exit $rc ) 2>/dev/null; then
      if timeout 120 "$L_BIN" "$W/a.txt" > "$W/b.txt" 2> "$W/err.txt" && cmp -s "$W/a.txt" "$W/b.txt"; then rs=$((rs+1)); else rd=$((rd+1)); echo "rust  $d $(head -c 200 "$W/err.txt")" >> "$W/differ.txt"; fi
    else
      rn=$((rn+1)); echo "nodump rust $d" >> "$W/differ.txt"
    fi
    if ( timeout 120 "$C_BIN" "$d" "$M" > "$W/c.txt"; rc=$?; exit $rc ) 2>/dev/null; then
      if timeout 120 "$L_BIN" "$W/c.txt" > "$W/e.txt" 2> "$W/err.txt" && cmp -s "$W/c.txt" "$W/e.txt"; then xs=$((xs+1)); else xd=$((xd+1)); echo "cross $d $(head -c 200 "$W/err.txt")" >> "$W/differ.txt"; fi
    else
      xn=$((xn+1)); echo "nodump $d" >> "$W/differ.txt"
    fi
  done < "$W/decks.txt"
  echo "ctxgate loadrt $M rust: $rs identical, $rd differ, $rn without a translation dump"
  echo "ctxgate loadrt $M cross: $xs identical, $xd differ, $xn without an upstream dump"
  head -${CTXGATE_SHOW:-5} "$W/differ.txt"
  [ -n "$CTXGATE_KEEP" ] && cp "$W/differ.txt" "$CTXGATE_KEEP"; rm -rf "$W"
  exit 0
fi

if [ "${1:-}" = init ] || [ "${1:-}" = start ] || [ "${1:-}" = step ] || [ "${1:-}" = helpers ]; then
  M=$1; NS=${2:-1}; [ "$M" = helpers ] && NS=${2:-10}; C_BIN="$H/gate/diff/ctxstep"; R_BIN="$E/ctxstep"
  same=0; diff=0; stubn=0; : > "$W/differ.txt"; : > "$W/stubs.txt"; : > "$W/reached.txt"; mkdir -p "$W/bak"
  if [ "$M" = step ]; then A2=(step "$NS" hash); elif [ "$M" = helpers ]; then A2=(helper "$NS" all "$W/side"); else A2=("$M"); fi
  while IFS= read -r d; do
    # back up the files the deck SAVEs to; restore them after each side's run
    python3 "$H/gate/savefiles.py" "$d" > "$W/saves.txt" 2>/dev/null; k=0
    while IFS= read -r f; do k=$((k+1)); rm -f "$W/bak/$k"; [ -f "$f" ] && cp -p "$f" "$W/bak/$k"; done < "$W/saves.txt"
    restore() { local k=0; while IFS= read -r f; do k=$((k+1)); if [ -f "$W/bak/$k" ]; then cp -p "$W/bak/$k" "$f"; else rm -f "$f"; fi; done < "$W/saves.txt"; }
    ( cd "$(dirname "$d")" && timeout 600 "$C_BIN" "$d" "${A2[@]}" > "$W/c.txt" 2>/dev/null; echo "exit $?" >> "$W/c.txt" ) 2>/dev/null; restore
    ( cd "$(dirname "$d")" && timeout 600 "$R_BIN" "$d" "${A2[@]}" > "$W/r.txt" 2>/dev/null; echo "exit $?" >> "$W/r.txt" ) 2>/dev/null; restore
    if cmp -s "$W/c.txt" "$W/r.txt"; then
      same=$((same+1))
      # what the deck reached: the return codes and the exit code (an all-crash would show here)
      echo "$(grep -aE '^(open|init|start)_rc ' "$W/c.txt" | tr '\n' ' ')$(grep -aE '^step [0-9]+ rc ' "$W/c.txt" | tail -1 | cut -d' ' -f1-4)$(grep -acE '^(skipped|.* skipped \()' "$W/c.txt" | sed 's/^0$//; s/^[1-9].*/ [some helpers skipped]/') $(tail -1 "$W/c.txt")" >> "$W/reached.txt"
      continue
    fi
    # a stub: the Rust side's last line before "exit 0" is "stub ...", and everything before
    # it matches upstream's output
    nr=$(wc -l < "$W/r.txt"); sl=$(sed -n "$((nr-1))p" "$W/r.txt")
    if [ "${sl%% *}" = stub ] && [ "$(tail -1 "$W/r.txt")" = "exit 0" ] && cmp -s <(head -n $((nr-2)) "$W/r.txt") <(head -n $((nr-2)) "$W/c.txt"); then
      stubn=$((stubn+1)); echo "$sl  $d" >> "$W/stubs.txt"; continue
    fi
    diff=$((diff+1)); echo "$d" >> "$W/differ.txt"
    if [ -n "$CTXGATE_DIFFDIR" ] && [ ! -f "$CTXGATE_DIFFDIR/c.txt" ]; then
      mkdir -p "$CTXGATE_DIFFDIR"; echo "$d" > "$CTXGATE_DIFFDIR/deck.txt"
      if [ "$M" = step ]; then
        # the first differing line names the step (hash <k> or step <k> ...)
        fl=$(cmp "$W/c.txt" "$W/r.txt" 2>/dev/null | sed -n 's/.* line \([0-9]*\).*/\1/p')
        lk=$(sed -n "${fl}p" "$W/c.txt"); set -- $lk; K=${2:-0}; [ "$K" = start ] && K=0
        ( cd "$(dirname "$d")" && timeout 600 "$C_BIN" "$d" step "$NS" full "$K" > "$CTXGATE_DIFFDIR/c.txt" 2>/dev/null ) 2>/dev/null; restore
        ( cd "$(dirname "$d")" && timeout 600 "$R_BIN" "$d" step "$NS" full "$K" > "$CTXGATE_DIFFDIR/r.txt" 2>/dev/null ) 2>/dev/null; restore
      else
        cp "$W/c.txt" "$CTXGATE_DIFFDIR/c.txt"; cp "$W/r.txt" "$CTXGATE_DIFFDIR/r.txt"
      fi
    fi
  done < "$W/decks.txt"
  echo "identical decks by what they reached:"; sort "$W/reached.txt" 2>/dev/null | uniq -c | sort -rn | head -${CTXGATE_SHOW_REACHED:-12}
  if [ "$M" = helpers ]; then
    echo "ctxgate helpers $NS: $same identical, $diff differ (stub reached on $stubn)"
  elif [ "$M" = step ]; then
    echo "ctxgate step $NS: $same identical, $stubn stopped at a stub, $diff differ"
    sed 's/  .*//' "$W/stubs.txt" | sort | uniq -c | sort -rn
  else
    echo "ctxgate $M: $same identical, $diff differ (stub reached on $stubn)"
  fi
  head -${CTXGATE_SHOW:-5} "$W/differ.txt"; head -3 "$W/stubs.txt"
  [ -n "$CTXGATE_KEEP" ] && cp "$W/differ.txt" "$CTXGATE_KEEP"; rm -rf "$W"
  exit 0
fi

PRE=""
case "${1:-}" in
  open) T=open; R=${2:-}; N=ctxopen ;;
  inithyd) T=inithyd; R=""; N=inithyd ;;
  inithydro) T=inithydro; R=${2:-}; N=inithydro ;;
  initqual) T=initqual; R=${2:-quality}; N=initqual
    [ "$R" = massbal ] && PRE=massref ;;
  *) T=${1:-ALL}; R=${2:-}; N=ctxread ;;
esac
C_BIN="$H/gate/diff/$N"; R_BIN="$E/$N"
same=0; diff=0; skipped=0; : > "$W/differ.txt"
while IFS= read -r d; do
  case $T in
    open|inithydro) A=("$d" ${R:-open}) ;;
    inithyd) A=("$d") ;;
    initqual) A=("$d" "$R" "$W/side.txt"); rm -f "$W/side.txt" ;;
    *) A=("$d" "$T" $R) ;;
  esac
  # (the subshells' stderr is dropped too: a harness that aborts, as both sides do on U1,
  # would otherwise print the shell's job notice)
  [ -n "$PRE" ] && ( cd "$(dirname "$d")" && timeout 120 "$C_BIN" "$d" "$PRE" "$W/side.txt" > /dev/null 2>&1 ) 2>/dev/null
  ( cd "$(dirname "$d")" && timeout 120 "$C_BIN" "${A[@]}" > "$W/c.txt" 2>/dev/null; echo "exit $?" >> "$W/c.txt"; timeout 120 "$R_BIN" "${A[@]}" > "$W/r.txt" 2>/dev/null; echo "exit $?" >> "$W/r.txt" ) 2>/dev/null
  [ "$T" = initqual ] && grep -q '^massbal skipped' "$W/c.txt" && skipped=$((skipped+1))
  if cmp -s "$W/c.txt" "$W/r.txt"; then same=$((same+1)); else diff=$((diff+1)); echo "$d" >> "$W/differ.txt"; fi
done < "$W/decks.txt"
if [ "$T" = initqual ]; then
  echo "ctxgate initqual $R: $same identical, $diff differ (massbal skipped on $skipped)"
else
  echo "ctxgate $T $R: $same identical, $diff differ"
fi
head -${CTXGATE_SHOW:-5} "$W/differ.txt"
[ -n "$CTXGATE_KEEP" ] && cp "$W/differ.txt" "$CTXGATE_KEEP"; rm -rf "$W"
