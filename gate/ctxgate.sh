#!/bin/bash
# The state gates: run every corpus deck, upstream test deck and gate/decks deck through
# upstream (the reference library, gate/diff/*) and through the translation
# (target/release/examples/*), dump the state, compare stdout and exit code. Build both
# sides first with gate/build.sh.
#
#   gate/ctxgate.sh [TAGS|ALL] [resolve]
#       parse: upstream's InputReader + handlers (gate/diff/ctxread) against examples/ctxread;
#       TAGS is a comma-separated list of sections or ALL. "resolve": both sides run
#       resolve_cross_references after reading.
#   gate/ctxgate.sh open [lenient|metadata]
#       the whole SWMMEngine::open (swmm_engine_open in gate/diff/ctxopen, examples/ctxopen),
#       then the context and the engine members open() sets; open_rc too. "lenient" sets
#       swmm_engine_set_lenient_open first; "metadata" opens through swmm_engine_open_metadata.
#   gate/ctxgate.sh inithyd
#       open, then SWMMEngine::initHydraulics (gate/diff/inithyd, examples/inithyd); dumps the
#       context, the open() members and the Router, controls, inflow, RDII, exfiltration,
#       inlet, structure and interface-file solvers (rtdump).
#   gate/ctxgate.sh inithydro [open|lenient|rdii]
#       open, then SWMMEngine::initHydrology (gate/diff/inithydro, examples/inithydro); dumps
#       the context, the open() members and the hydrology solver members (hydrodump).
#       "rdii" runs rdii_.init first, as initHydraulics does.
#   gate/ctxgate.sh initqual quality|geometry|massbal
#       open, then one of SWMMEngine::initQuality / initGeometry / initMassBalance
#       (gate/diff/initqual, examples/initqual); dumps the context, the open() members and the
#       quality members. massbal first runs
#       `initqual deck massref side` (upstream's own initialize, in its own process) for the
#       hydrology solver state initMassBalance reads; see gate/diff/initqual.cpp.
#   gate/ctxgate.sh loadrt [open|lenient|metadata|init]
#       the context loader (examples/common/ctxload.rs, generated by tools/ctxload.py). Per deck:
#         rust:  examples/ctxopen dump -> examples/ctxload (load into a fresh engine, dump
#                again) -> cmp
#         cross: gate/diff/ctxopen (upstream) dump -> examples/ctxload -> cmp with upstream's text
#       "init" dumps upstream after swmm_engine_initialize too; the translation has no
#       initialize yet, so only the cross test runs. A deck upstream aborts on (no dump) is
#       counted apart.
#   gate/ctxgate.sh route [K1 [K0]]
#       the routing-step cross test (default calls 1..300). Per deck, upstream
#       (gate/diff/routestep) is opened, initialized and started through its C API and stepped
#       with swmm_engine_step; the harness's own SWMMEngine::stepRouting (the library calls it
#       through its PLT) dumps the whole state before and after the library's stepRouting for
#       calls K0..K1 (context, rtdump, qualdump, stepdump). examples/routestep then, for each
#       call, opens the deck, runs the translated init legs, loads upstream's BEFORE dump
#       (ctxload: load, load_rt, load_qual), runs the translated step_routing with upstream's
#       dt and dumps. gate/routecmp.py compares: first the loader's round trip (load, dump,
#       cmp with the BEFORE block), then every AFTER block. Results: identical, differ (first
#       call and label), loaddiff, nottranslated (the translation stops on a path it does not
#       translate yet), nostart (upstream's open/initialize/start failed), nosteps.
#       CTXGATE_LOG=file appends one line per deck.
#
# DECKLIST=file runs the decks listed in it (one path per line) instead of the default set.
# CTXGATE_KEEP=file keeps the list of differing decks; CTXGATE_SHOW=n shows the first n.
H=$(cd "$(dirname "$0")/.." && pwd); W=$(mktemp -d)
E="$H/target/release/examples"
if [ -n "$DECKLIST" ]; then sort "$DECKLIST" > "$W/decks.txt"      # DECKLIST=file: one deck path per line
else { find /root/work/corpus -name '*.inp'; find /root/work/swmm6src/upstream/tests -name '*.inp'; find "$H/gate/decks" -name '*.inp'; } | sort > "$W/decks.txt"; fi

if [ "${1:-}" = route ]; then
  K1=${2:-300}; K0=${3:-1}; C_BIN="$H/gate/diff/routestep"; R_BIN="$E/routestep"
  : > "$W/res.txt"
  while IFS= read -r d; do
    ( cd "$(dirname "$d")" && timeout 600 "$C_BIN" "$d" "$K0" "$K1" > "$W/c.txt" 2>/dev/null
      timeout 1200 "$R_BIN" "$d" "$W/c.txt" load > "$W/l.txt" 2> "$W/err.txt"
      timeout 1200 "$R_BIN" "$d" "$W/c.txt" > "$W/r.txt" 2>> "$W/err.txt" ) 2>/dev/null
    res=$(python3 "$H/gate/routecmp.py" "$W/c.txt" "$W/r.txt" "$W/l.txt" 2>&1 | head -1)
    [ -s "$W/err.txt" ] && grep -q panicked "$W/err.txt" && res="panic $(grep -m1 -A1 panicked "$W/err.txt" | tail -1 | head -c 160)"
    echo "$res $d" >> "$W/res.txt"
    [ -n "$CTXGATE_LOG" ] && echo "$res $d" >> "$CTXGATE_LOG"
  done < "$W/decks.txt"
  for k in identical differ loaddiff nottranslated nostart nosteps panic; do
    printf '%s %s\n' "$k" "$(grep -c "^$k " "$W/res.txt")"
  done | tr '\n' ' '; echo "(route calls $K0..$K1)"
  grep -v '^identical \|^nostart \|^nosteps ' "$W/res.txt" | head -${CTXGATE_SHOW:-5}
  [ -n "$CTXGATE_KEEP" ] && cp "$W/res.txt" "$CTXGATE_KEEP"; rm -rf "$W"
  exit 0
fi

if [ "${1:-}" = loadrt ]; then
  M=${2:-open}; C_BIN="$H/gate/diff/ctxopen"; R_BIN="$E/ctxopen"; L_BIN="$E/ctxload"
  rs=0; rd=0; xs=0; xd=0; xn=0; : > "$W/differ.txt"
  while IFS= read -r d; do
    cd "$(dirname "$d")" || continue
    if [ "$M" != init ]; then
      timeout 120 "$R_BIN" "$d" "$M" > "$W/a.txt" 2>/dev/null
      if timeout 120 "$L_BIN" "$W/a.txt" > "$W/b.txt" 2> "$W/err.txt" && cmp -s "$W/a.txt" "$W/b.txt"; then rs=$((rs+1)); else rd=$((rd+1)); echo "rust  $d $(head -c 200 "$W/err.txt")" >> "$W/differ.txt"; fi
    fi
    if ( timeout 120 "$C_BIN" "$d" "$M" > "$W/c.txt"; rc=$?; exit $rc ) 2>/dev/null; then
      if timeout 120 "$L_BIN" "$W/c.txt" > "$W/e.txt" 2> "$W/err.txt" && cmp -s "$W/c.txt" "$W/e.txt"; then xs=$((xs+1)); else xd=$((xd+1)); echo "cross $d $(head -c 200 "$W/err.txt")" >> "$W/differ.txt"; fi
    else
      xn=$((xn+1)); echo "nodump $d" >> "$W/differ.txt"
    fi
  done < "$W/decks.txt"
  [ "$M" != init ] && echo "ctxgate loadrt $M rust: $rs identical, $rd differ"
  echo "ctxgate loadrt $M cross: $xs identical, $xd differ, $xn without an upstream dump"
  head -${CTXGATE_SHOW:-5} "$W/differ.txt"
  [ -n "$CTXGATE_KEEP" ] && cp "$W/differ.txt" "$CTXGATE_KEEP"; rm -rf "$W"
  exit 0
fi

PRE=""
case "${1:-}" in
  open) T=open; R=${2:-}; N=ctxopen ;;
  inithyd) T=inithyd; R=""; N=inithyd ;;
  inithydro) T=inithydro; R=${2:-}; N=inithydro ;;
  initqual) T=initqual; R=${2:-quality}; N=initqual
    [ "$R" = massbal ] && PRE=massref ;;
  *) T=${1:-ALL}; R=${2:-}; N=ctxread ;;
esac
C_BIN="$H/gate/diff/$N"; R_BIN="$E/$N"
same=0; diff=0; skipped=0; : > "$W/differ.txt"
while IFS= read -r d; do
  case $T in
    open|inithydro) A=("$d" ${R:-open}) ;;
    inithyd) A=("$d") ;;
    initqual) A=("$d" "$R" "$W/side.txt"); rm -f "$W/side.txt" ;;
    *) A=("$d" "$T" $R) ;;
  esac
  # (the subshells' stderr is dropped too: a harness that aborts, as both sides do on U1,
  # would otherwise print the shell's job notice)
  [ -n "$PRE" ] && ( cd "$(dirname "$d")" && timeout 120 "$C_BIN" "$d" "$PRE" "$W/side.txt" > /dev/null 2>&1 ) 2>/dev/null
  ( cd "$(dirname "$d")" && timeout 120 "$C_BIN" "${A[@]}" > "$W/c.txt" 2>/dev/null; echo "exit $?" >> "$W/c.txt"; timeout 120 "$R_BIN" "${A[@]}" > "$W/r.txt" 2>/dev/null; echo "exit $?" >> "$W/r.txt" ) 2>/dev/null
  [ "$T" = initqual ] && grep -q '^massbal skipped' "$W/c.txt" && skipped=$((skipped+1))
  if cmp -s "$W/c.txt" "$W/r.txt"; then same=$((same+1)); else diff=$((diff+1)); echo "$d" >> "$W/differ.txt"; fi
done < "$W/decks.txt"
if [ "$T" = initqual ]; then
  echo "ctxgate initqual $R: $same identical, $diff differ (massbal skipped on $skipped)"
else
  echo "ctxgate $T $R: $same identical, $diff differ"
fi
head -${CTXGATE_SHOW:-5} "$W/differ.txt"
[ -n "$CTXGATE_KEEP" ] && cp "$W/differ.txt" "$CTXGATE_KEEP"; rm -rf "$W"
