#!/usr/bin/env python3
"""Generate the 2D initialization gate decks in gate/decks/twodi/.

SurfaceRouter2D::initialize() has paths no other gate deck reaches with an active mesh:

  np_*     pollutant-free copies of the gate/decks/twod/ parser decks that carry [POLLUTANTS]
           (and the quality rows naming them), so their meshes, initial velocities, node maps,
           boundary rows, conveyance rows, infiltration rows and options run through
           initialize() instead of stopping at the phase-2b species-transport refusal
  nc_*     [2D_NODE_COUPLING] rows on the coupled example: every junction type, every key,
           CREST/COEFFS/LAW choices, NONE, a coupleable node without a map row, outfall SPREAD
           and TAILWATER_RELAX
  cpl_*    coupling set-up warnings: map rows without a CD under COUPLING_CD 0, an outfall
           without links, sur_depth and ponded_area on a coupled junction, a node on another
           vertical datum, COUPLING_POND_MODE under KINWAVE
  inf_*    infiltration set-up: INFIL_DEFAULT_METHOD NONE/conflicting/without a '*' row,
           INFILTRATION NO with rows and YES without, INFIL_DESTINATION SUBCATCH_AQUIFER (cells
           outside every polygon and inside two), and the refusals (no subcatchments,
           AQUIFER_2D)
  opt_*    the engine options the router reads: THREADS 2, IGNORE_2D, a zero-slope NORMAL_FLOW
           edge, a WALL_DRAG row on a missing cell

The 1D reference build skips the [2D_*] sections with a warning, so these are 1D gate decks too.
Run from anywhere: `python3 gate/twodi_gen.py`.

Written for swmm6-rust, 12 November 2026, by Claude (Anthropic) for Robert Dickinson. The coupled
decks derive from OpenSWMM's examples/2d_complete_example.inp (Copyright 2026 Caleb Buahin,
Apache License, Version 2.0) through gate/twodc_gen.py; the header of each generated deck says so.
"""
import os, re, sys

H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(H, 'gate'))
import twodc_gen as tc  # noqa: E402

OUT = os.path.join(H, 'gate', 'decks', 'twodi')
TWOD = os.path.join(H, 'gate', 'decks', 'twod')

HEADER_LOT = tc.HEADER.replace('gate/twodc_gen.py', 'gate/twodi_gen.py')
HEADER_NP = (';; swmm6-rust gate deck {name}: {what}\n'
             ';; Generated by gate/twodi_gen.py from swmm6-rust gate/decks/twod/{src}.inp. Not an OpenSWMM file.\n')

# the parser decks whose [POLLUTANTS] row stops initialize() at the species-transport refusal
NP_SOURCES = [
    'tw_badopt_18', 'tw_badopt_44', 'tw_durations', 'tw_groundwater_yes', 'tw_gw_bcs',
    'tw_gw_et_alias', 'tw_gw_opts_only', 'tw_infil', 'tw_infil_noalias', 'tw_mesh_ft_header',
    'tw_mesh_rows', 'tw_mesh_si_header', 'tw_mesh_si_variants', 'tw_meshfile', 'tw_options_b',
    'tw_options_c', 'tw_options_d', 'tw_output_file', 'tw_rain_mesh', 'tw_rain_none', 'tw_sq',
    'tw_vj_uncoupled',
]
# the ones whose wall drag, Coriolis or turbulence rows need FULL_SWE on a global step
NP_SWE = {'tw_mesh_rows', 'tw_mesh_si_header', 'tw_options_b'}
NP_DROP = {'POLLUTANTS', '2D_INITIAL_QUALITY', '2D_INITIAL_BED_QUALITY', '2D_BOUNDARY_QUALITY',
           '2D_COVERAGES', '2D_LOADINGS'}


def write_lot(name, what, secs):
    p = os.path.join(OUT, name + '.inp')
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER_LOT.format(name=name, what=what))
        f.write(tc.join(secs))


def np_decks():
    n = 0
    for src in NP_SOURCES:
        with open(os.path.join(TWOD, src + '.inp'), 'rb') as f:
            text = f.read().decode('latin-1')
        secs = [(nm, b) for nm, b in tc.sections(text) if nm not in NP_DROP]
        mf = tc.get(secs, '2D_MESH_FILE')
        if mf is not None:
            # the mesh files stay next to the source deck
            mf = re.sub(r'^(\s*FILE\s+)(\S+)', lambda m: m.group(1) + '../twod/' + m.group(2), mf,
                        flags=re.M | re.I)
            secs = tc.put(secs, '2D_MESH_FILE', mf)
        name = 'np_' + src[3:]
        with open(os.path.join(OUT, name + '.inp'), 'wb') as f:
            f.write(HEADER_NP.format(name=name, what='%s without pollutants' % src, src=src).encode('latin-1'))
            f.write(tc.join(secs).encode('latin-1'))
        n += 1
        if src in NP_SWE:
            o = tc.get(secs, '2D_OPTIONS') or ''
            for k, v in (('MOMENTUM_EQUATION', 'FULL_SWE'), ('LTS_TIERS', '1')):
                o = tc.set_opt(o, k, v)
            secs2 = tc.put(list(secs), '2D_OPTIONS', o + '\n')
            name2 = name + '_swe'
            with open(os.path.join(OUT, name2 + '.inp'), 'wb') as f:
                f.write(HEADER_NP.format(name=name2, what='%s without pollutants, FULL_SWE and LTS_TIERS 1' % src,
                                         src=src).encode('latin-1'))
                f.write(tc.join(secs2).encode('latin-1'))
            n += 1
    return n


def with_rows(s, section, rows, after):
    return tc.put(s, section, rows + '\n\n', after=after)


def opt2d(s, kv):
    o = tc.get(s, '2D_OPTIONS')
    for k, v in kv:
        o = tc.set_opt(o, k, v)
    return tc.put(s, '2D_OPTIONS', o)


def nc_decks():
    n = 0
    cases = [
        ('nc_grate', 'J1 GRATE (WEIR_ORIFICE, every geometry key, CREST MESH_BED), ST1 OPEN with a chamber',
         'J1   GRATE  LAW=WEIR_ORIFICE PERIMETER=2.4 AREA=0.5 CHAMBER_AREA=1.5 CREST=MESH_BED COEFFS=RUBINATO2017_UPPER CW=0.6\n'
         'ST1  OPEN   LAW=WEIR_ORIFICE CHAMBER_AREA=8'),
        ('nc_curb', 'J1 CURB (diameter, lid opening, CREST MAX, each coefficient), ST1 OPEN with DEFAULT coefficients',
         'J1   CURB   LAW=WEIR_ORIFICE D=0.9 LID_OPEN_FRACTION=0.5 CREST=MAX CSW=0.04 COI=0.15 COO=0.14\n'
         'ST1  OPEN   LAW=WEIR_ORIFICE COEFFS=DEFAULT CREST=MIN'),
        ('nc_manhole', 'J1 MANHOLE (ORIFICE, diameter and chamber), ST1 OPEN (ORIFICE)',
         'J1   MANHOLE D=1.5 CHAMBER_AREA=3\n'
         'ST1  OPEN'),
        ('nc_manhole_weir', 'J1 MANHOLE under WEIR_ORIFICE with CREST NODE_RIM and RUBINATO2017_LOWER',
         'J1   MANHOLE LAW=WEIR_ORIFICE CREST=NODE_RIM COEFFS=RUBINATO2017_LOWER\n'
         'ST1  OPEN    LAW=WEIR_ORIFICE COEFFS=RUBINATO2017'),
        ('nc_none', 'J1 authored NONE: its vertex map row is ignored',
         'J1   NONE'),
    ]
    for name, what, rows in cases:
        s = tc.base_lot()
        s = with_rows(s, '2D_NODE_COUPLING', rows, '2D_TRIANGLE_NODE_MAP')
        write_lot(name, what, s); n += 1
    # the weir/orifice law from the options, the rows only naming structures
    s = tc.base_lot()
    s = opt2d(s, [('COUPLING_LAW', 'WEIR_ORIFICE')])
    s = with_rows(s, '2D_NODE_COUPLING', 'J1   GRATE  PERIMETER=3\nST1  OPEN', '2D_TRIANGLE_NODE_MAP')
    write_lot('nc_law_option', 'COUPLING_LAW WEIR_ORIFICE with a GRATE row and an OPEN row', s); n += 1
    # a coupleable node without a map row; an outfall's SPREAD and TAILWATER_RELAX
    s = tc.base_outfall(False)
    s = with_rows(s, '2D_NODE_COUPLING', 'JX    MANHOLE D=1.0\nOUT3  OUTFALL SPREAD=6 TAILWATER_RELAX=30', '2D_TRIANGLE_NODE_MAP')
    write_lot('nc_outfall_spread', 'outfall SPREAD/TAILWATER_RELAX and a coupleable junction without a map row', s); n += 1
    s = tc.base_outfall(True)
    s = with_rows(s, '2D_NODE_COUPLING', 'OUT3  OUTFALL SPREAD=25', '2D_TRIANGLE_NODE_MAP')
    write_lot('nc_outfall_spread_wide', 'a gated outfall spreading over the whole mesh', s); n += 1
    s = tc.base_outfall(False)
    s = with_rows(s, '2D_NODE_COUPLING', 'OUT3  NONE', '2D_TRIANGLE_NODE_MAP')
    write_lot('nc_outfall_none', 'an outfall authored NONE: its cell map row is ignored', s); n += 1
    return n


def cpl_decks():
    n = 0
    s = tc.base_lot()
    s = opt2d(s, [('COUPLING_CD', '0')])
    s = tc.put(s, '2D_VERTEX_NODE_MAP', '   4       J1\n\n')
    s = tc.put(s, '2D_TRIANGLE_NODE_MAP', '   vault   ST1\n\n')
    write_lot('cpl_cd_zero', 'COUPLING_CD 0 with map rows that author no CD', s); n += 1
    s = tc.base_lot()
    s = tc.put(s, '2D_VERTEX_NODE_MAP', '   4       J1\n\n')
    s = tc.put(s, '2D_TRIANGLE_NODE_MAP', '   vault   ST1   *   6.0\n\n')
    write_lot('cpl_cd_default', 'map rows without a CD under the example COUPLING_CD', s); n += 1
    # an outfall with no link mapped twice
    s = tc.base_lot()
    s = tc.put(s, 'OUTFALLS', tc.get(s, 'OUTFALLS').rstrip('\n') + '\nOUT9    99.0       FREE   *          NO\n\n')
    s = tc.put(s, '2D_TRIANGLE_NODE_MAP', tc.get(s, '2D_TRIANGLE_NODE_MAP').rstrip('\n') + '\n   1   OUT9   0.6   1.0\n   2   OUT9   0.6   1.0\n\n')
    s = tc.put(s, '2D_VERTEX_NODE_MAP', tc.get(s, '2D_VERTEX_NODE_MAP').rstrip('\n') + '\n   0   OUT9   0.6   1.0\n\n')
    s = tc.put(s, 'COORDINATES', tc.get(s, 'COORDINATES').rstrip('\n') + '\nOUT9     5.0       2.0\n\n')
    write_lot('cpl_unused_outfall', 'an outfall without links mapped to a vertex and two cells', s); n += 1
    # surcharge depth and ponded area on the coupled junction
    s = tc.base_lot()
    s = tc.put(s, 'JUNCTIONS', tc.get(s, 'JUNCTIONS').replace(
        'J1      99.0       1.5       0.0        0.0       0.0', 'J1      99.0       1.5       0.2        0.5       12.0'))
    write_lot('cpl_surdepth_ponded', 'the coupled junction authors sur_depth, ponded_area and an initial depth', s); n += 1
    # the junction on another datum (rim 1000.5 m against a 100..101 m mesh)
    s = tc.base_lot()
    s = tc.put(s, 'JUNCTIONS', tc.get(s, 'JUNCTIONS').replace(
        'J1      99.0       1.5       0.0        0.0       0.0', 'J1      999.0      1.5       0.0        0.0       0.0'))
    s = tc.put(s, 'OUTFALLS', tc.get(s, 'OUTFALLS').replace('OUT1    98.0', 'OUT1    998.0'))
    write_lot('cpl_datum', 'the vertex-coupled junction sits 900 m above the mesh', s); n += 1
    # pond mode and rim band under kinematic wave
    s = tc.base_routing('KINWAVE')
    s = opt2d(s, [('COUPLING_POND_MODE', 'CHAMBER'), ('COUPLING_RIM_BAND', '0.05')])
    write_lot('cpl_pond_kinwave', 'COUPLING_POND_MODE CHAMBER and COUPLING_RIM_BAND under KINWAVE', s); n += 1
    # tracking pond with the stencil head on the quad mesh
    s = tc.base_quads()
    s = opt2d(s, [('COUPLING_POND_MODE', 'TRACKING'), ('COUPLING_HEAD', 'STENCIL_WET_MEAN'), ('COUPLING_AREA', 'AUTO')])
    write_lot('cpl_quads_tracking', 'quads with a tracking pond, stencil head and AUTO areas', s); n += 1
    # US units: CFS with the example mesh in feet
    s = tc.base_lot()
    s = tc.put(s, 'OPTIONS', tc.set_opt(tc.get(s, 'OPTIONS'), 'FLOW_UNITS', 'CFS'))
    write_lot('cpl_cfs', 'the coupled example under FLOW_UNITS CFS', s); n += 1
    return n


SUBS = ('[SUBCATCHMENTS]\n;;Name  Raingage  Outlet  Area  %Imperv  Width  %Slope  CurbLen\n'
        'S1      RG1       J1      0.02  50       100    0.5     0\n'
        'S2      RG1       J1      0.02  50       100    0.5     0\n\n')


def subs(s):
    s = tc.put(s, 'SUBCATCHMENTS', SUBS.split('\n', 1)[1], after='RAINGAGES')
    s = tc.put(s, 'SUBAREAS', ';;Subcatch  N-Imperv  N-Perv  S-Imperv  S-Perv  PctZero  RouteTo\n'
                              'S1          0.01      0.1     0.05      0.05    25       OUTLET\n'
                              'S2          0.01      0.1     0.05      0.05    25       OUTLET\n\n', after='SUBCATCHMENTS')
    s = tc.put(s, 'INFILTRATION', ';;Subcatch  Suction  Ksat  IMD\nS1          3.0      0.5   0.25\nS2          3.0      0.5   0.25\n\n',
               after='SUBAREAS')
    # S1 covers the west half; S2 the south strip from x = 5 (T0's centroid lies in both);
    # the north-east cells lie in neither
    s = tc.put(s, 'POLYGONS', ';;Subcatch  X  Y\nS1  0 0\nS1  10 0\nS1  10 20\nS1  0 20\n'
                              'S2  5 0\nS2  20 0\nS2  20 10\nS2  5 10\n\n', after='COORDINATES')
    return s


def no_dest(s):
    """The '*' row without its DEST token, so INFIL_DESTINATION decides."""
    return tc.put(s, '2D_INFILTRATION_DEFAULTS', tc.get(s, '2D_INFILTRATION_DEFAULTS').replace(' LOST', ''))


def inf_decks():
    n = 0
    s = tc.base_infil('HORTON')
    s = opt2d(s, [('INFIL_DEFAULT_METHOD', 'NONE')])
    write_lot('inf_default_none', "INFIL_DEFAULT_METHOD NONE drops the '*' row", s); n += 1
    s = tc.base_infil('HORTON')
    s = opt2d(s, [('INFIL_DEFAULT_METHOD', 'GREEN_AMPT')])
    write_lot('inf_default_conflict', "INFIL_DEFAULT_METHOD GREEN_AMPT against a HORTON '*' row (2D initialization fails)", s); n += 1
    s = tc.base_infil('HORTON')
    s = opt2d(s, [('INFIL_DEFAULT_METHOD', 'HORTON')])
    write_lot('inf_default_match', "INFIL_DEFAULT_METHOD HORTON matching the '*' row", s); n += 1
    s = tc.base_infil('GREEN_AMPT')
    s = tc.put(s, '2D_INFILTRATION_DEFAULTS', 'vault GREEN_AMPT 101.6 12.7 0.3 0 0 LOST\n\n')
    s = opt2d(s, [('INFIL_DEFAULT_METHOD', 'CONSTANT')])
    write_lot('inf_default_nostar', "INFIL_DEFAULT_METHOD CONSTANT with only a tag row", s); n += 1
    s = tc.base_infil('CONSTANT')
    s = opt2d(s, [('INFILTRATION', 'NO')])
    write_lot('inf_no_with_rows', 'INFILTRATION NO with a default row', s); n += 1
    s = tc.base_lot()
    s = opt2d(s, [('INFILTRATION', 'YES')])
    write_lot('inf_yes_no_rows', 'INFILTRATION YES without rows', s); n += 1
    s = tc.base_infil('HORTON')
    s = opt2d(s, [('INFIL_DESTINATION', 'AQUIFER_2D')])
    write_lot('inf_dest_aquifer2d', 'INFIL_DESTINATION AQUIFER_2D (obsolete: 2D initialization fails)', s); n += 1
    s = no_dest(tc.base_infil('HORTON'))
    s = opt2d(s, [('INFIL_DESTINATION', 'SUBCATCH_AQUIFER')])
    write_lot('inf_subaq_nosub', 'INFIL_DESTINATION SUBCATCH_AQUIFER without subcatchments (2D initialization fails)', s); n += 1
    s = subs(no_dest(tc.base_infil('HORTON')))
    s = opt2d(s, [('INFIL_DESTINATION', 'SUBCATCH_AQUIFER')])
    write_lot('inf_subaq', 'INFIL_DESTINATION SUBCATCH_AQUIFER over two subcatchment polygons', s); n += 1
    s = subs(tc.base_infil('GREEN_AMPT'))
    s = tc.put(s, '2D_INFILTRATION_DEFAULTS', '* GREEN_AMPT 101.6 12.7 0.3 0 0 SUBCATCH_AQUIFER\n'
                                              'vault GREEN_AMPT 101.6 12.7 0.3 0 0 LOST\n\n')
    write_lot('inf_subaq_rows', 'a SUBCATCH_AQUIFER default row and a LOST tag row', s); n += 1
    return n


def opt_decks():
    n = 0
    s = tc.base_lot()
    s = tc.put(s, 'OPTIONS', tc.set_opt(tc.get(s, 'OPTIONS'), 'THREADS', '2'))
    write_lot('opt_threads2', 'the coupled example with THREADS 2', s); n += 1
    s = tc.base_lot()
    s = tc.put(s, 'OPTIONS', tc.set_opt(tc.get(s, 'OPTIONS'), 'IGNORE_2D', 'YES'))
    write_lot('opt_ignore_2d', 'the coupled example with IGNORE_2D YES', s); n += 1
    s = tc.base_lot()
    s = tc.put(s, '2D_BOUNDARY_CONDITIONS', tc.get(s, '2D_BOUNDARY_CONDITIONS').replace(
        '   0     2      NORMAL_FLOW       0.0050', '   0     2      NORMAL_FLOW       0.0'))
    write_lot('opt_normal_zero', 'a NORMAL_FLOW edge with zero slope', s); n += 1
    s = tc.base_lot()
    s = tc.put(s, '2D_BOUNDARY_CONDITIONS', tc.get(s, '2D_BOUNDARY_CONDITIONS').rstrip('\n') +
               '\n   99    0      WALL_DRAG         0.05            *         *\n\n')
    write_lot('opt_wall_drag_bad', 'a WALL_DRAG row on a missing cell (2D initialization fails)', s); n += 1
    s = tc.base_lot()
    s = tc.put(s, '2D_BOUNDARY_CONDITIONS', tc.get(s, '2D_BOUNDARY_CONDITIONS').rstrip('\n') +
               '\n   99    0      WALL              0               *         *\n\n')
    write_lot('opt_wall_missing', 'a plain WALL row on a missing cell (skipped)', s); n += 1
    return n


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.inp'):
            os.remove(os.path.join(OUT, f))
    n = np_decks() + nc_decks() + cpl_decks() + inf_decks() + opt_decks()
    print('twodi_gen: %d decks in %s' % (n, OUT))


if __name__ == '__main__':
    main()
