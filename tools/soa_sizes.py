#!/usr/bin/env python3
"""Structural differential for structure-of-arrays stores.

For each (header, struct, rust path, ops) case, writes a C++ harness that includes
upstream's header, runs the ops on a default-constructed struct and prints the length of
every std::vector field after each op; and a Rust example that does the same on the
translation. The two outputs must be identical: same fields sized, same lengths, after
every op. It checks sizing only, not values.

Usage: soa_sizes.py  (writes gate/diff/sizes.cpp and crates/engine/examples/sizes.rs)
"""
import re, os

UP = '/root/work/swmm6src/upstream/src/engine/data'
ROOT = '/root/work/swmm6-rust'
RUST_KEYWORDS = {'type', 'match', 'loop', 'move', 'ref', 'self', 'fn', 'mod', 'use', 'impl', 'in', 'where', 'box'}

# (header, struct, rust type path, ops). Ops are C++ calls on `s`; Rust calls are derived
# by converting camelCase method names to snake_case.
CASES = [
    ('NodeData.hpp', 'NodeData', 'swmm6_rust::data::node::NodeData',
     ['resize(5)', 'resize_quality(3)', 'resize_loads(2)', 'grow_to(8)', 'erase_at(2)', 'grow_to(3)', 'resize(0)', 'resize_quality(0)']),
    ('SubcatchData.hpp', 'SubcatchData', 'swmm6_rust::data::subcatch::SubcatchData',
     ['resize(4)', 'resize_quality(3)', 'resize_washoff_load(2)', 'resize_total_load(4, 3)', 'resize_coverage(4, 2)',
      'grow_to(7)', 'erase_at(1)', 'reserve_to(20)', 'save_state()', 'reset_state()', 'resize(2)']),
    ('GageData.hpp', 'GageData', 'swmm6_rust::data::gage::GageData',
     ['resize(3)', 'grow_to(6)', 'erase_at(0)', 'reset_state()', 'resize(1)']),
    ('LinkData.hpp', 'LinkData', 'swmm6_rust::data::link::LinkData',
     ['resize(6)', 'resize_quality(3)', 'resize_loads(2)', 'grow_to(9)', 'erase_at(4)', 'reserve_to(30)', 'save_state()', 'reset_state()', 'resize(1)']),
    ('PollutantData.hpp', 'PollutantData', 'swmm6_rust::data::pollutant::PollutantData',
     ['resize_pollutants(4)', 'resize_pollutants(2)']),
]

def strip(src):
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'//[^\n]*', '', src)
    return re.sub(r'(std::vector<[\w:<> ]+>)\s*\n\s*(\w+\s*;)', r'\1 \2', src)

def vec_fields(header, struct):
    src = strip(open(os.path.join(UP, header)).read())
    m = re.search(r'struct\s+' + struct + r'\s*\{', src)
    i = m.end(); d = 1
    while d:
        d += {'{': 1, '}': -1}.get(src[i], 0); i += 1
    body = src[m.end():i - 1]
    # only top-level declarations (depth 0 inside the struct)
    out = []; depth = 0
    for line in body.split('\n'):
        s = line.strip()
        if depth == 0:
            fm = re.fullmatch(r'std::vector<[\w:<> ]+>\s+(\w+)\s*;', s)
            if fm:
                out.append(fm.group(1))
        depth += s.count('{') - s.count('}')
    return out

def snake(op):
    name, rest = op.split('(', 1)
    name = re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()
    return f'{name}({rest}'

def main():
    cpp = ['// generated by tools/soa_sizes.py', '#include <cstdio>']
    rs = ['// generated by tools/soa_sizes.py: Rust side of gate/diff/sizes.cpp', 'fn main() {']
    for header, struct, path, ops in CASES:
        cpp.append(f'#include "{header}"')
    cpp.append('using namespace openswmm;')
    cpp.append('int main() {')
    for header, struct, path, ops in CASES:
        fields = vec_fields(header, struct)
        cpp.append(f'  {{ {struct} s; std::printf("== {struct}\\n");')
        rs.append(f'    {{ let mut s = {path}::default(); println!("== {struct}");')
        for op in ['/*init*/'] + ops:
            if op != '/*init*/':
                cpp.append(f'    s.{op};')
                rs.append(f'        s.{snake(op)};')
            cpp.append(f'    std::printf("-- {op}\\n");')
            rs.append(f'        println!("-- {op}");')
            for f in fields:
                rf = f + '_' if f in RUST_KEYWORDS else f
                cpp.append(f'    std::printf("{f} %zu\\n", s.{f}.size());')
                rs.append(f'        println!("{f} {{}}", s.{rf}.len());')
        cpp.append('  }')
        rs.append('    }')
    cpp.append('}')
    rs.append('}')
    open(f'{ROOT}/gate/diff/sizes.cpp', 'w').write('\n'.join(cpp) + '\n')
    open(f'{ROOT}/crates/engine/examples/sizes.rs', 'w').write('\n'.join(rs) + '\n')

if __name__ == '__main__':
    main()
